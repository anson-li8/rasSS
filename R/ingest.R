# ============================================================================
# REFERENCE PREP
# ============================================================================
# This package assumes you have a PLINK binary reference panel an a dosage 
# matrix for your target genomic block.
#
# 1. Create EUR keep-list (from 1000G panel file):
#    Get-Content integrated_call_samples_v3.20130502.ALL.panel |
#      Where-Object { ($_ -split "`t")[2] -eq "EUR" } |
#      ForEach-Object { $i = ($_ -split "`t")[0]; "$i $i" } |
#      Set-Content -Encoding ASCII eur_samples_2col.txt
#
# 2. Create full-chromosome binary files (restrict to biallelic SNPs, MAF>1%):
#    plink2 --vcf <chr>.vcf.gz --double-id --keep eur_samples_2col.txt \
#           --maf 0.01 --max-alleles 2 --snps-only just-acgt --rm-dup exclude-all \
#           --make-bed --out chr_eur
#
# 3. Extract target block and export dosages (snps_keep.txt generated by write_snp_list):
#    plink2 --bfile chr_eur --extract snps_keep.txt --make-bed --out block
#    plink2 --bfile block --export A --out block_dosage
# ============================================================================

#' Read GWAS summary statistics into a standardized table
#'
#' Auto-detects common column schemas (CNCR/Savage, PGC, GCST). Derives Z from
#' beta/SE, or from P and effect sign when Z is absent. Handles files with or 
#' without an Effect Allele Frequency (EAF) column.
#'
#' @param path Path to (optionally gzipped) delimited sumstat file.
#' @param chr Optional chromosome to subset.
#' @param start_bp,end_bp Optional base-pair window.
#' @return A \code{data.table} with standardized columns: snp, chr, bp, a1, a2, z, beta, eaf.
#' @export
read_sumstats <- function(path, chr = NULL, start_bp = NULL, end_bp = NULL) {
  nms <- names(data.table::fread(path, nrows = 0))
  pick <- function(pats) {
    for (p in pats) { i <- grep(p, nms, ignore.case = TRUE); if (length(i)) return(nms[i[1]]) }
    NA_character_
  }
  found <- c(
    snp  = pick(c("^snp$", "^rsid", "^markername$", "^variantid$", "^id$")),
    chr  = pick(c("^chr$", "^chrom$", "^chromosome$")),
    bp   = pick(c("^pos$", "^bp$", "^base_pair", "^position$")),
    a1   = pick(c("^a1$", "^effect_allele$", "^ea$", "^allele1$")),
    a2   = pick(c("^a2$", "^other_allele$", "^oa$", "^allele2$")),
    z    = pick(c("^z$", "^zscore", "^z_score$")),
    beta = pick(c("^stdbeta$", "^beta$", "^effect$", "^b$")),
    or   = pick(c("^or$", "^odds_ratio$")),
    se   = pick(c("^se$", "^stderr", "^standard_error$")),
    p    = pick(c("^p$", "^pvalue", "^p_value$")),
    eaf  = pick(c("^eaf", "^effect_allele_freq", "^fcon$", "^fcas$", "^freq", "^maf$", "^frq"))
  )
  
  # EAF is optional (some PGC files lack it), but snp, a1, a2 are mandatory
  if (any(is.na(found[c("snp", "a1", "a2")])))
    stop("Missing required columns. Detected: ", paste(names(found), found, sep = "=", collapse = ", "))
  
  std  <- names(found)[!is.na(found)]          # standard names
  file <- as.character(found[!is.na(found)])   # names as they appear in the file
  dt <- data.table::as.data.table(data.table::fread(path, select = unique(file)))
  cat("[read_sumstats] read:", nrow(dt), "rows,", ncol(dt), "cols\n")
  
  data.table::setnames(dt, old = file, new = std)
  stopifnot(all(c("snp", "a1", "a2") %in% names(dt)))
  
  # Derive beta from OR if needed
  if (!is.null(dt$or) && is.null(dt$beta)) dt$beta <- log(dt$or)
  
  # Derive Z if missing
  if (is.null(dt$z)) {
    if (!is.null(dt$beta) && !is.null(dt$se)) {
      dt$z <- dt$beta / dt$se
    } else if (!is.null(dt$beta) && !is.null(dt$p)) {
      dt$z <- sign(dt$beta) * stats::qnorm(dt$p / 2, lower.tail = FALSE)
    } else {
      stop("No Z column and cannot derive one from beta/SE or P.")
    }
  }
  
  # Filter by chromosome
  if (!is.null(chr)) {
    if (is.null(dt$chr)) stop("chr requested but no chromosome column detected.")
    dt <- dt[which(as.numeric(dt$chr) == chr), ]
    cat("[read_sumstats] after chr filter:", nrow(dt), "\n")
  }
  
  # Filter by base-pair window
  if (!is.null(start_bp)) {
    if (is.null(dt$bp)) stop("bp window requested but no position column detected.")
    dt <- dt[which(dt$bp >= start_bp & dt$bp <= end_bp), ]
    cat("[read_sumstats] after bp filter:", nrow(dt), "\n")
  }
  
  # Drop missing critical data and standardize alleles to uppercase
  dt <- dt[which(!is.na(dt$z) & !is.na(dt$a1) & !is.na(dt$a2)), ]
  dt$a1 <- toupper(dt$a1)
  dt$a2 <- toupper(dt$a2)
  
  # Enforce canonical column order
  canonical <- c("snp", "chr", "bp", "a1", "a2", "eaf", "z", "beta", "se", "p")
  data.table::setcolorder(dt, intersect(canonical, names(dt)))
  
  cat("[read_sumstats] final:", nrow(dt), "\n")
  dt
}

#' Run one genomic block end-to-end
#'
#' Intersects discovery/target sumstats with the reference, extracts and exports
#' dosages via PLINK2, harmonizes, scans, and calls peaks. Idempotent when
#' \code{out_rds} exists.
#'
#' @param disc_path Path to discovery GWAS summary statistics.
#' @param targ_path Path to target GWAS summary statistics.
#' @param chr Chromosome number.
#' @param start_bp Block start position (base pairs).
#' @param end_bp Block end position (base pairs).
#' @param ref_prefix Prefix of the PLINK binary reference panel (bfile stem).
#' @param plink2 Path to the plink2 executable.
#' @param out_rds Output \code{.rds} path; if it exists, the call is skipped.
#' @param skip1 Number of leading SNPs skipped during the scan (discovery side).
#' @param skip2 Number of leading SNPs skipped during the scan (target side).
#' @param min_window_size Minimum CPD window size in SNPs.
#' @param max_window_size Maximum CPD window size in SNPs.
#' @param window_size CPD window size used for peak calling.
#' @param slope_check_window_size CPD slope-check window size.
#' @param slope_threshold CPD slope p-value threshold.
#' @param davies_threshold CPD Davies p-value threshold.
#' @param max_snps Maximum allowed SNPs after intersection.
#' @return A list with \code{peaks}, \code{scan}, \code{n_intersect}, \code{n_kept},
#'   \code{n_in}.
#' @export
scan_block <- function(disc_path, targ_path, chr, start_bp, end_bp, ref_prefix,
                       plink2 = "plink2", out_rds = NULL,
                       skip1 = 10, skip2 = 5, min_window_size = 5, max_window_size = 20,
                       window_size = 20, slope_check_window_size = 8,
                       slope_threshold = 1e-4, davies_threshold = 1e-5,
                       max_snps = 25000) {
  if (!is.null(out_rds) && file.exists(out_rds)) {
    cat("skip: exists", out_rds, "\n"); return(invisible(readRDS(out_rds)))
  }
  disc <- read_sumstats(disc_path, chr = chr, start_bp = start_bp, end_bp = end_bp)
  targ <- read_sumstats(targ_path, chr = chr, start_bp = start_bp, end_bp = end_bp)
  bim  <- read_bim(paste0(ref_prefix, ".bim"))
  keep <- Reduce(intersect, list(disc$snp, targ$snp, bim$id))
  cat("intersect:", length(keep), "\n")
  stopifnot(length(keep) >= 500, length(keep) <= max_snps)
  
  snplist <- tempfile(fileext = ".txt"); writeLines(keep, snplist)
  blk <- tempfile("block")
  run <- function(...) {
    r <- system2(plink2, c(...), stdout = TRUE, stderr = TRUE)
    if (!is.null(attr(r, "status")) && attr(r, "status") != 0)
      stop("plink2 failed:\n", paste(utils::tail(r, 20), collapse = "\n"))
    invisible(r)
  }
  run("--bfile", ref_prefix, "--extract", snplist, "--make-bed", "--out", blk)
  run("--bfile", blk, "--export", "A", "--out", blk)
  
  ld    <- ld_matrix(paste0(blk, ".raw"))
  bim_b <- read_bim(paste0(blk, ".bim"))
  h     <- harmonize_two(disc, targ, bim_b, ld)
  cat("kept:", h$n_kept, "of", h$n_in, "\n")
  stopifnot(h$n_kept / h$n_in >= 0.6)
  
  scan <- scan_ss(h$w, h$Z, h$R, mask = rep(TRUE, length(h$w)),
                  skip1 = skip1, skip2 = skip2,
                  min_window_size = min_window_size, max_window_size = max_window_size)
  pk   <- call_peaks(scan, h$bp, window_size = window_size,
                     slope_check_window_size = slope_check_window_size,
                     slope_threshold = slope_threshold,
                     davies_threshold = davies_threshold, skip = skip1)
  res  <- list(disc = disc_path, targ = targ_path, chr = chr,
               start = start_bp, end = end_bp, n_intersect = length(keep),
               n_kept = h$n_kept, n_in = h$n_in, scan = scan, peaks = pk)
  if (!is.null(out_rds)) saveRDS(res, out_rds)
  res
}

#' Read a PLINK .bim file into a standardized table
#'
#' @param path Path to a PLINK .bim file.
#' @return A \code{data.table} with columns id, bp, a1, a2.
#' @export
read_bim <- function(path) {
  b <- data.table::fread(path, header = FALSE)
  data.table::setnames(b, c("chr", "id", "cm", "bp", "a1", "a2"))
  b[, c("id", "bp", "a1", "a2"), with = FALSE]
}

#' Write an rsID list for PLINK --extract
#' 
#' @param sumstats Output of \code{\link{read_sumstats}}.
#' @param path Output file path.
#' @export
write_snp_list <- function(sumstats, path) writeLines(sumstats$snp, path)

#' Build LD matrix from a PLINK dosage export
#' 
#' Reads a PLINK2 \code{--export A} .raw file. Extracts the "counted" allele 
#' from the column name suffix (e.g., \code{rs123_A} -> \code{A}) to provide 
#' exact allele orientation without relying on EAF.
#'
#' @param raw_path Path to the .raw file.
#' @return List with G (dosages), R (correlation LD), ids, freq, and counted allele.
#' @export
ld_matrix <- function(raw_path) {
  raw <- data.table::fread(raw_path)
  nms <- names(raw)[7:ncol(raw)]
  ids <- sub("_[^_]*$", "", nms)
  tok <- sub("^[^_]*_", "", nms)
  
  # If all suffixes are single A/C/G/T, we know exactly which allele PLINK counted
  counted <- if (all(tok %in% c("A", "C", "G", "T"))) tok else NULL
  
  G <- as.matrix(raw[, 7:ncol(raw), with = FALSE])
  colnames(G) <- ids
  
  # Drop monomorphic SNPs to prevent NA correlations
  v <- apply(G, 2, stats::var)
  G <- G[, v > 0, drop = FALSE]
  if (!is.null(counted)) counted <- counted[v > 0]
  
  list(G = G, R = stats::cor(G), ids = colnames(G), freq = colMeans(G) / 2,
       counted = counted)
}

#' Internal helper for allele orientation
#' @keywords internal
.orient <- function(sumstats, bim, ld, freq_tol) {
  bim2 <- bim[bim$id %in% ld$ids, ]
  d <- sumstats[match(bim2$id, sumstats$snp), ]
  miss <- is.na(d$snp)
  
  a1 <- toupper(d$a1); a2 <- toupper(d$a2)
  B1 <- toupper(bim2$a1); B2 <- toupper(bim2$a2)
  allele_ok <- !miss & ((a1 == B1 & a2 == B2) | (a1 == B2 & a2 == B1))
  
  # Drop palindromic SNPs (A/T, C/G)
  pal <- (a1 == "A" & a2 == "T") | (a1 == "T" & a2 == "A") |
    (a1 == "C" & a2 == "G") | (a1 == "G" & a2 == "C")
  
  m <- match(bim2$id, ld$ids)
  cnt <- if (!is.null(ld$counted)) toupper(ld$counted[m]) else rep(NA_character_, length(m))
  have_cnt <- !is.na(cnt)
  
  flip <- rep(NA, length(m))
  flip[have_cnt & a1 == cnt] <- FALSE
  flip[have_cnt & a2 == cnt] <- TRUE
  
  # Fallback to EAF frequency matching if counted allele is missing
  if (!is.null(d$eaf)) {
    f <- ld$freq[m]
    md <- abs(d$eaf - f) < freq_tol
    mc <- abs((1 - d$eaf) - f) < freq_tol
    eaf_flip <- mc & !md
    use <- is.na(flip) & (md != mc)
    flip[use & md] <- FALSE
    flip[use & mc] <- TRUE
    disagree <- have_cnt & (md != mc) & (flip != eaf_flip)
    ok <- allele_ok & !pal & !is.na(flip) & !disagree
  } else {
    ok <- allele_ok & !pal & !is.na(flip)
  }
  
  Z <- d$z
  w <- if (!is.null(d$beta)) d$beta else d$z
  fs <- ok & flip
  Z[fs] <- -Z[fs]; w[fs] <- -w[fs]
  
  list(bim = bim2, ok = ok, Z = Z, w = w)
}

#' Harmonize sumstats against an LD reference (single study)
#'
#' Orients Z and weights to the allele the dosage matrix counts. Uses the exact
#' counted allele from PLINK if available, falling back to the EAF frequency 
#' match (XOR rule). Drops palindromic SNPs and frequency-ambiguous SNPs.
#'
#' @param sumstats Output of \code{\link{read_sumstats}}.
#' @param bim Output of \code{\link{read_bim}}.
#' @param ld Output of \code{\link{ld_matrix}}.
#' @param freq_tol Maximum |EAF - reference frequency| tolerance.
#' @return List with w, Z, bp, R, ids, n_kept, all aligned to each other.
#' @export
harmonize <- function(sumstats, bim, ld, freq_tol = 0.15) {
  o <- .orient(sumstats, bim, ld, freq_tol)
  m <- match(o$bim$id, ld$ids)
  k <- o$ok
  list(w = o$w[k], Z = o$Z[k], bp = o$bim$bp[k], R = ld$R[m[k], m[k]],
       ids = o$bim$id[k], n_kept = sum(k), n_in = length(k))
}

#' Harmonize two independent sumstats against an LD reference
#'
#' Used for valid inference where discovery weights (\code{w}) and target 
#' Z-scores (\code{Z}) must come from independent cohorts.
#'
#' @param disc Discovery sumstats (provides weights \code{w}).
#' @param targ Target sumstats (provides Z-scores \code{Z}).
#' @param bim Output of \code{\link{read_bim}}.
#' @param ld Output of \code{\link{ld_matrix}}.
#' @param freq_tol Maximum |EAF - reference frequency| tolerance.
#' @return List with w, Z, bp, R, ids, n_kept, all aligned to each other.
#' @export
harmonize_two <- function(disc, targ, bim, ld, freq_tol = 0.15) {
  od <- .orient(disc, bim, ld, freq_tol)
  ot <- .orient(targ, bim, ld, freq_tol)
  k <- od$ok & ot$ok
  m <- match(od$bim$id, ld$ids)
  list(w = od$w[k], Z = ot$Z[k], bp = od$bim$bp[k], R = ld$R[m[k], m[k]],
       ids = od$bim$id[k], n_kept = sum(k), n_in = length(k))
}

#' Run RAS change-point detection and map peaks to base pairs
#' 
#' Wraps \code{RAS::ras_detect} and \code{RAS::ras_validate}. Correctly maps 
#' the validated \code{tau_hats} (which are full-SNP-scale indices) back to 
#' base-pair positions.
#'
#' @param scan Output of \code{\link{scan_ss}}.
#' @param bp_per_snp Base-pair positions aligned to the SNPs given to scan_ss.
#' @param window_size CPD window size.
#' @param slope_check_window_size CPD slope check window.
#' @param slope_threshold CPD slope p-value threshold.
#' @param davies_threshold CPD Davies p-value threshold.
#' @param min_signal Minimum RAS height to validate a peak.
#' @param skip The \code{skip1} parameter used in \code{scan_ss}.
#' @return List with snp_index, grid_index, and bp.
#' @export
call_peaks <- function(scan, bp_per_snp, window_size = 20,
                       slope_check_window_size = 8, slope_threshold = 1e-4,
                       davies_threshold = 1e-5, min_signal = 2.5, skip = 10) {
  x <- seq_along(scan$y)
  cp <- quiet(RAS::ras_detect(x = x, y = scan$y, window_size = window_size,
                              slope_check_window_size = slope_check_window_size,
                              slope.p.values.threshold.left = slope_threshold,
                              slope.p.values.threshold.right = slope_threshold))
  val <- quiet(RAS::ras_validate(this.result = cp, x = x, y = scan$y,
                                 this.start = 1, this.skip = skip,
                                 second_window_size = window_size,
                                 min_signal = min_signal,
                                 p.value.threshold = davies_threshold))
  
  # ras_validate rescales by this.skip: tau_hats are FULL-SNP-scale indices
  snp_idx <- unique(val$tau_hats)
  snp_idx <- snp_idx[!is.na(snp_idx) & snp_idx >= 1 & snp_idx <= length(bp_per_snp)]
  
  list(snp_index = snp_idx,
       grid_index = match(snp_idx, scan$x),
       bp = bp_per_snp[snp_idx])
}